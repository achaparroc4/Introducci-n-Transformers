import numpy as np

# -------------------------
# 1. FRASE Y VOCABULARIO
# -------------------------

frase = "esta frase es una prueba pequeña"

palabras = frase.split()

vocabulario = {
    word: i
    for i, word in enumerate(palabras)
}

token_ids = [vocabulario[token] for token in palabras]

vocab_size = len(vocabulario)


# -------------------------
# 2. DIMENSIONES
# -------------------------

dimension = 4
d_k = 2


# -------------------------
# 3. EMBEDDINGS
# -------------------------

E = np.random.randn(vocab_size, dimension)

X = E[token_ids]


# -------------------------
# 4. PROYECCIONES
# -------------------------

W_Q = np.random.randn(dimension, d_k)
W_K = np.random.randn(dimension, d_k)
W_V = np.random.randn(dimension, d_k)

Q = X @ W_Q
K = X @ W_K
V = X @ W_V


# -------------------------
# 5. PUNTAJES DE ATENCIÓN
# -------------------------

puntajes = (Q @ K.T) / np.sqrt(d_k)


# -------------------------
# 6. SOFTMAX
# -------------------------

def softmax(x):
    exp_x = np.exp(
        x - np.max(x, axis=1, keepdims=True)
    )

    return exp_x / np.sum(
        exp_x,
        axis=1,
        keepdims=True
    )


pesos_atencion = softmax(puntajes)


# -------------------------
# 7. SALIDA DE ATENCIÓN
# -------------------------

Y = pesos_atencion @ V


# -------------------------
# 8. MOSTRAR RESULTADOS
# -------------------------

print("Palabras:")
print(palabras)

print("\nVocabulario:")
print(vocabulario)

print("\nToken IDs:")
print(token_ids)

print("\nDimensiones:")
print("E:", E.shape)
print("X:", X.shape)
print("Q:", Q.shape)
print("K:", K.shape)
print("V:", V.shape)
print("Puntajes:", puntajes.shape)
print("Pesos de atención:", pesos_atencion.shape)
print("Y:", Y.shape)

print("\nPesos de atención:")
print(pesos_atencion)

print("\nSalida Y:")
print(Y)

import matplotlib.pyplot as plt

# Crear el mapa de calor
plt.figure(figsize=(8, 6))

plt.imshow(pesos_atencion, cmap="viridis")

# Etiquetas de los ejes
plt.xticks(range(len(palabras)), palabras, rotation=45)
plt.yticks(range(len(palabras)), palabras)

plt.xlabel("Tokens a los que se presta atención (Keys)")
plt.ylabel("Tokens que prestan atención (Queries)")

plt.title("Mapa de calor de los pesos de atención")

# Mostrar los valores dentro de cada celda
for i in range(len(palabras)):
    for j in range(len(palabras)):
        plt.text(
            j, i,
            f"{pesos_atencion[i, j]:.2f}",
            ha="center",
            va="center",
            color="white"
        )

plt.colorbar(label="Peso de atención")
plt.tight_layout()
plt.show()